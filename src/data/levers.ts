export interface LeverItem {
  id?: string; // Phase 1: kebab-case from name, populated by codemod-levers.ts
  name: string;
  nameEn?: string;
  nameJa?: string;
  nameKo?: string;
  ministry: string; // 部委或机构（中文，遇到 CJK 必须配 ministryEn）
  /** English sibling of `ministry`. Required if `ministry` contains CJK. */
  ministryEn?: string;
  ministryJa?: string;
  ministryKo?: string;
  scale?: string; // 金额、规模、KPI
  scaleEn?: string;
  scaleJa?: string;
  scaleKo?: string;
  description: string;
  descriptionEn?: string;
  descriptionJa?: string;
  descriptionKo?: string;
  sourceUrl?: string;
  // Phase 1 cross-refs (hand-curated over time).
  relatedPolicyIds?: string[];
  relatedDebateIds?: string[];
}

export interface LeverGroup {
  title: string; // 子分组标题（如"外资引进的算力（EDB）"）
  titleEn?: string;
  titleJa?: string;
  titleKo?: string;
  items: LeverItem[];
}

export interface Lever {
  number: number; // 1–6
  icon: string;
  name: string; // 中文名
  nameEn?: string;
  nameJa?: string;
  nameKo?: string;
  subtitle: string; // 一句话定位
  subtitleEn?: string;
  subtitleJa?: string;
  subtitleKo?: string;
  whatStateDoes: string; // 国家直接做的事
  whatStateDoesEn?: string;
  whatStateDoesJa?: string;
  whatStateDoesKo?: string;
  bottleneckSolved: string; // 解决企业的什么瓶颈
  bottleneckSolvedEn?: string;
  bottleneckSolvedJa?: string;
  bottleneckSolvedKo?: string;
  transmissionMode: 'direct' | 'transmitted'; // 国家直接做 vs 穿透到企业
  groups: LeverGroup[];
  insight?: string; // 一句锐利判断
  insightEn?: string;
  insightJa?: string;
  insightKo?: string;
  // Phase 1 cross-refs (hand-curated over time).
  championPersonIds?: string[];
  relatedPolicyIds?: string[];
  relatedPostSlugs?: string[];
  /** YYYY-MM-DD; the date this lever was first added to the repo. Used by
   *  src/utils/derived-updates.ts to surface a homepage "Recent updates" entry.
   *  Old records may be undefined → not surfaced. */
  addedAt?: string;
}

